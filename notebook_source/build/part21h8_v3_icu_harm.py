XV3_HARM_LAMBDAS = tuple(float(x) for x in np.round(np.linspace(0.0, 1.0, 11), 10))
XV3_HARM_GROUPS = ("main", "reference")
XV3_HARM_COLUMNS = ["source", "policy", "seed", "draw", "group", "main_table", "method", "variant", "lambda", "status",
                    "return", "prob_any_violation", "expected_violations"]
assert XV3_HARM_LAMBDAS[0] == 0.0 and XV3_HARM_LAMBDAS[-1] == 1.0 and np.all(np.diff(XV3_HARM_LAMBDAS) > 0)


def x_harm_env(env: FiniteEnv, lam: float) -> FiniteEnv:
    """P_lambda: unsupported live rows (1 - lam) * P + lam * e_sink; supported and absorbing rows bitwise unchanged."""
    lam = float(lam)
    assert 0.0 <= lam <= 1.0, lam
    P = env.P.copy()
    bad = ~env.mask & env.live[:, None]
    P[bad] *= 1.0 - lam
    P[bad, env.sink] += lam
    return env.variant(f"{env.name}|harm{lam:g}", P=P, harm_lambda=lam)


def x_harm_curves(env: FiniteEnv, policies: Sequence[dict], lambdas: Sequence[float]) -> pd.DataFrame:
    """J(lambda) of every policy (dicts with 'pi' and the descriptive XV3_HARM_COLUMNS keys) on x_harm_env(env, lambda)."""
    keys = [_x_pi_key(p["pi"]) for p in policies]
    rows = []
    for lam in lambdas:
        env_l = x_harm_env(env, lam)
        memo: Dict[bytes, dict] = {}
        for p, k in zip(policies, keys):
            if k not in memo:
                memo[k] = _x_v3_eval(env_l, p["pi"], "given")
            ev = memo[k]
            rows.append({**{c: p.get(c, np.nan) for c in XV3_HARM_COLUMNS[:8]}, "lambda": float(lam),
                         "status": ev["status"],
                         **{c: ev.get(c, np.nan) for c in ("return", "prob_any_violation", "expected_violations")}})
        del env_l, memo
        gc.collect()
    return pd.DataFrame(rows, columns=XV3_HARM_COLUMNS)


def x_harm_part1_policies() -> List[dict]:
    """REGISTRY policies of the groups main and reference at the first main seed (FIXED for fixed policies)."""
    seed0 = int(CFG.seeds[0])
    out = []
    for name, e in REGISTRY.items():
        if e.group not in XV3_HARM_GROUPS:
            continue
        seed = seed0 if seed0 in e.by_seed else (FIXED if FIXED in e.by_seed else None)
        if seed is None:
            continue
        out.append({"source": "part1", "policy": name, "seed": int(seed), "draw": np.nan, "group": e.group,
                    "main_table": name in MAIN_TABLE_POLICIES, "method": e.family, "variant": e.mask_use,
                    "pi": validate_policy(e.by_seed[seed], f"{name} seed={seed}", shape=(X_ICU.S, X_ICU.A))})
    return out


def x_harm_part1(policies: List[dict]) -> pd.DataFrame:
    """Part I curves (cached; pure evaluation, so a miss is computed even when ALLOW_TRAINING is False)."""
    identity = {"kind": "xenv_v3_icu_harm_part1", "x_icu": X_ICU.identity(), "code": XV3_HARM_CODE_HASH,
                "lambdas": list(XV3_HARM_LAMBDAS),
                "policies": sorted([p["policy"], int(p["seed"]), array_hash(p["pi"])] for p in policies)}
    key = "v3harm/part1"
    hit = XCACHE.get(key, identity)
    if hit is not None:
        return hit
    XCACHE.put(key, identity, x_harm_curves(X_ICU, policies, XV3_HARM_LAMBDAS))
    return XCACHE.get(key, identity)


def x_harm_icu_spec() -> dict:
    spec = {"cell": "icu|released", "family": "icu", "draws": int(XCFG.icu_draws),
            "user_episodes": int(XCFG.icu_user_episodes)}
    hit = [s for s in X_CELLS if s["cell"] == "icu|released"]
    if hit:
        assert hit[0] == spec, f"icu|released spec differs from x_build_cells: {hit[0]}"
    return spec


def x_harm_part2() -> Tuple[pd.DataFrame, Dict[str, Any]]:
    """Part II curves of the ICU draw-0 default policies (regenerated with run_xmethods; cached)."""
    spec = x_harm_icu_spec()
    inst = build_cell_instance(spec, 0)
    assert all(np.array_equal(inst.data[k], OFFLINE[k]) for k in ("state", "action", "next_state", "episode_id")), \
        "ICU draw 0 must be the Part I dataset (OFFLINE)"
    identity = {"kind": "xenv_v3_icu_harm_part2", "draw": x_draw_identity(spec, inst), "code": XV3_HARM_CODE_HASH,
                "lambdas": list(XV3_HARM_LAMBDAS)}
    key = "v3harm/" + x_cache_key("icu|released", 0)
    hit = XCACHE.get(key, identity)
    if hit is not None:
        return hit, {"cache": "loaded"}
    XCACHE.require_allowed(key)
    t0 = time.perf_counter()
    raw = run_xmethods(LearnerView.from_env(inst.learn_env), inst.train, "icu|released|draw0")
    recs = [r for r in x_collect_records(raw, inst.behavior, inst.learn_env) if r["is_default"]]
    del raw
    pols = [{"source": "part2", "policy": r["label"], "seed": np.nan, "draw": 0, "group": "default",
             "main_table": False, "method": r["method"], "variant": r["variant"], "pi": r["pi"]} for r in recs]
    t1 = time.perf_counter()
    XCACHE.put(key, identity, x_harm_curves(inst.learn_env, pols, XV3_HARM_LAMBDAS))
    del inst, recs, pols
    gc.collect()
    return XCACHE.get(key, identity), {"cache": "computed", "methods_s": t1 - t0, "curves_s": time.perf_counter() - t1}


def x_harm_endpoints(curves: pd.DataFrame, ref: pd.DataFrame, keys: Sequence[str]) -> Dict[str, Any]:
    """|J(lambda) - reference| at lambda in {0, 1}; `ref` has columns keys + ['lambda', 'return_ref']."""
    if curves.empty or ref.empty:
        return {"rows": 0, "missing_reference": None, "max_abs_diff": None, "rows_above_tol": 0,
                "status": "not compared (no curves or no reference rows)"}
    m = curves[curves["lambda"].isin([0.0, 1.0])].merge(ref, on=[*keys, "lambda"], how="left", validate="one_to_one")
    d = (m["return"] - m["return_ref"]).abs()
    return {"rows": int(len(m)), "missing_reference": int(m["return_ref"].isna().sum()),
            "nonok_curve_rows": int((m["status"] != "ok").sum()),
            "max_abs_diff": float(d.max()) if d.notna().any() else None, "rows_above_tol": int((d > XV3_TOL).sum()),
            "status": "compared"}


def x_harm_pair_stats(J: np.ndarray, lambdas: Sequence[float], tol: float = XV3_TOL) -> Tuple[List[dict], Dict[str, int]]:
    """Per-lambda ranking statistics of J [n_policies, n_lambda] (lambda ascending; column 0 = mean, -1 = terminate)."""
    J = np.asarray(J, dtype=np.float64)
    n, L = J.shape
    pairs = n * (n - 1) // 2
    iu = np.triu_indices(n, 1)
    D = (J[:, None, :] - J[None, :, :])[iu]                       # [pairs, L], i < j
    S = np.where(D > tol, 1, np.where(D < -tol, -1, 0))
    robust = (S != 0).all(axis=1) & (S == S[:, :1]).all(axis=1)
    cert = J[:, -1][:, None] > J[:, 0][None, :] + tol           # lower(i) > upper(j)
    np.fill_diagonal(cert, False)
    cert_u = cert[iu] | cert.T[iu]
    sign_c = np.where(cert[iu], 1, -1)                            # direction of a certified pair
    checks = {"certified_order_violations": int((cert_u & ((D * sign_c[:, None]).min(axis=1) <= 0)).sum()),
              "certified_not_lambda_robust": int((cert_u & ~robust).sum()),
              "bracket_violations": int(((J < J[:, -1:] - tol) | (J > J[:, :1] + tol)).sum()),
              "monotonicity_violations": int((np.diff(J, axis=1) > tol).sum()),
              "both_directions_certified": int((cert & cert.T).sum())}
    s0 = xs_snap_ties(J[:, 0]) if n else J[:, 0]
    rows = []
    for l, lam in enumerate(lambdas):
        sl = xs_snap_ties(J[:, l]) if n else J[:, l]
        tau = (float(stats.kendalltau(s0, sl)[0]) if n >= 2 and np.ptp(s0) > 0 and np.ptp(sl) > 0 else np.nan)
        rev = int(((S[:, 0] * S[:, l]) < 0).sum())
        rows.append({"lambda": float(lam), "n_policies": int(n), "pairs": int(pairs), "kendall_tau_b_vs_lambda0": tau,
                     "ordered_pairs": int((S[:, l] != 0).sum()), "reversals_vs_lambda0": rev,
                     "reversal_share": rev / pairs if pairs else np.nan, "certified_pairs": int(cert.sum()),
                     "certified_share": int(cert.sum()) / pairs if pairs else np.nan,
                     "lambda_robust_pairs": int(robust.sum()),
                     "lambda_robust_share": int(robust.sum()) / pairs if pairs else np.nan})
    return rows, checks


XV3_HARM_SETS = (("part1", "all", None), ("part1", "main_table", True), ("part2", "default", None))


def x_harm_summary(curves: pd.DataFrame) -> Tuple[pd.DataFrame, Dict[str, Any]]:
    """Ranking statistics per policy set and lambda over the policies proper at every lambda; pooled checks."""
    rows, checks = [], {}
    for source, name, main_only in XV3_HARM_SETS:
        d = curves[curves["source"] == source]
        if main_only:
            d = d[d["main_table"].astype(bool)]
        if d.empty:
            continue
        idx = ["policy", "seed"] if source == "part1" else ["policy", "draw"]
        J = d.set_index(idx + ["lambda"])["return"].unstack("lambda").reindex(columns=list(XV3_HARM_LAMBDAS))
        ok = d.groupby(idx)["status"].agg(lambda s: bool((s == "ok").all())).reindex(J.index)
        Jok = J[ok.to_numpy()]
        r, c = x_harm_pair_stats(Jok.to_numpy(), XV3_HARM_LAMBDAS)
        rows += [{"source": source, "policy_set": name, "policies_total": int(len(J)),
                  "policies_not_proper_everywhere": int((~ok).sum()), **x} for x in r]
        checks[f"{source}/{name}"] = {**c, "policies": int(len(Jok)), "not_proper_everywhere": int((~ok).sum())}
    return pd.DataFrame(rows), checks


def xs_fig_v3_icu_harm(curves: pd.DataFrame, summary: pd.DataFrame, fig_dir: Path) -> str:
    """(a) J(lambda) of the Part I main-table policies; (b) Kendall tau-b against the lambda = 0 ranking."""
    d = curves[(curves["source"] == "part1") & curves["main_table"].astype(bool) & (curves["status"] == "ok")]
    if d.empty or summary.empty:
        return "not produced: no Part I main-table harm curves"
    J = d.set_index(["policy", "lambda"])["return"].unstack("lambda").dropna()
    width = (J[0.0] - J[1.0]).sort_values(ascending=False)
    top = [p for p in width.index[:4] if width[p] > XV3_TOL]
    fig, axes = plt.subplots(1, 2, figsize=(10.5, 3.8))
    ax = axes[0]
    lam = np.asarray(J.columns, dtype=float)
    for p in J.index:
        if p not in top:
            ax.plot(lam, J.loc[p].to_numpy(), color=XS_MUTED, lw=1.0, alpha=0.55, zorder=1)
    for i, p in enumerate(top):
        ax.plot(lam, J.loc[p].to_numpy(), color=XS_COLORS[i], lw=2.0, marker="o", ms=4, zorder=3,
                label=f"{p} (width {width[p]:.3f})")
    ax.plot([], [], color=XS_MUTED, lw=1.0, label=f"other main-table policies ({len(J) - len(top)})")
    ax.set_xlabel("harm λ of unsupported actions (0 = mean rule, 1 = terminate)")
    ax.set_ylabel("exact return J(λ) on ICU-Sepsis")
    ax.set_title("(a) Part I main-table policies, seed 0", loc="left", color=XS_INK)
    ax.legend(fontsize=7, frameon=False, loc="upper left", bbox_to_anchor=(0.0, -0.2))
    ax = axes[1]
    labels = {("part1", "all"): "Part I, main + reference", ("part1", "main_table"): "Part I, main table",
              ("part2", "default"): "Part II, ICU draw 0 defaults"}
    for i, ((src, nm), g) in enumerate(summary.groupby(["source", "policy_set"], sort=False)):
        g = g.sort_values("lambda")
        cs = float(g["certified_share"].iloc[0])
        ax.plot(g["lambda"], g["kendall_tau_b_vs_lambda0"], color=XS_COLORS[i], lw=2.0, marker="o", ms=4,
                label=f"{labels.get((src, nm), f'{src} {nm}')}: n = {int(g['n_policies'].iloc[0])}, "
                      f"certified {100 * cs:.0f}% of pairs")
    ax.set_xlabel("harm λ")
    ax.set_ylabel("Kendall τ-b vs the λ = 0 ranking")
    ax.set_title("(b) ranking agreement with the mean rule", loc="left", color=XS_INK)
    ax.legend(fontsize=7, frameon=False, loc="upper left", bbox_to_anchor=(0.0, -0.2))
    return _xs_save(fig, fig_dir, "fig_v3_icu_harm")


