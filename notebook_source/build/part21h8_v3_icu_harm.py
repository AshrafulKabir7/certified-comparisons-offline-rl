# %% [markdown]
# ### II.8h ICU-Sepsis harm curves J(λ)
#
# ICU-Sepsis has no ground truth for unsupported actions, but the bracketing theorem needs none: only the completion
# is unknown. This section traces the identified interval of every policy along the **intermediate-harm** family
#
# P_λ(·|s, a) = (1 − λ)·P_mean(·|s, a) + λ·e_death  for live s and a ∉ M(s),  λ ∈ {0, 0.1, …, 1},
#
# on the released rows (`X_ICU`, the adapter verified against `EVALUATOR` in II.3a). Supported rows are left
# bitwise unchanged (`x_harm_env`). λ = 0 is the mean rule and λ = 1 the termination rule; ICU-Sepsis pays 0 on death,
# so r_term = v_min. By the theorem, every P_λ is a truth that satisfies no hidden benefit, so
# J_term(π) ≤ J_λ(π) ≤ J_mean(π) for every policy. Applying the same identity to two harm levels also makes
# J_λ non-increasing in λ. A certified pair (J_term(i) > J_mean(j)) is therefore ordered at every λ. The cell asserts
# all three facts, and that the endpoints reproduce the reported values to 1e-9: λ = 0 matches `RESULTS` (mean) and
# the `XRESULTS` `bench_mean` rows, and λ = 1 matches the terminate rule and `bench_terminate`.
#
# **Policies.**
# * Part I: every `REGISTRY` entry of the groups `main` and `reference`, at the first main seed (`CFG.seeds[0]`), or
#   at `FIXED` for a fixed policy. `main_table` marks the policies of `MAIN_TABLE_POLICIES`.
# * Part II: the default policies of ICU draw 0 (the Part I dataset). They are regenerated by running `run_xmethods`
#   on the II.6 training split of `icu|released` draw 0, under the same key as II.6, plus the behaviour policy and
#   the projections (`x_collect_records`).
#
# **Reported per policy set and λ** (`xenv/v3_icu_harm_summary.csv`), over the policies that are proper at every λ:
# Kendall τ-b between the λ = 0 ranking and the λ ranking (ties within 1e-9 snapped, as in II.7); the number of pairs
# whose strict order at λ = 0 is reversed at λ; the certified pairs (λ-free); and the λ-robust pairs, strictly ordered
# the same way at every grid λ. Certified pairs are a subset of the λ-robust pairs.
#
# Both curve tables are cached in `XCACHE`. Part II: key `v3harm/icu_released/draw0`, with the II.6 draw identity,
# the code hash of this section and the λ grid. Part I: key `v3harm/part1`, with the hashes of the evaluated policy
# arrays and the `X_ICU` identity. Part I curves are pure evaluation, so they are computed even with
# `ALLOW_TRAINING = False`.
#
# **Expected cost on Colab.** About 120 policies × 11 λ exact solves on the 716-state model (about 30–60 ms each),
# plus one `run_xmethods` fit on ICU draw 0 (about 30 s in the II.6 timings): about 2–3 min in total.
#
# | Output | Content |
# |---|---|
# | `xenv/v3_icu_harm_curves.csv` | source (part1 / part2), policy, seed or draw, group, `main_table`, λ, status, return, P(any unsupported decision), expected violations |
# | `xenv/v3_icu_harm_summary.csv` | per policy set and λ: τ-b against λ = 0, reversals, certified and λ-robust pairs and shares |
# | `xenv/v3_icu_harm_checks.json` | endpoint identities, bracketing, monotonicity and certified-order checks; `passes` |
# | `figures/xenv/fig_v3_icu_harm.*` | (a) J(λ) of the Part I main-table policies; (b) τ-b(λ) against the mean-rule ranking per policy set |

